            <div class="card-body">
                <h3 class="h5">What are "Reality Checks"?</h3>
                <p>Reality checks are simple tests you perform during the day to see if you’re dreaming. If you make them a habit, you’ll eventually perform one while asleep. Popular checks include:</p>
                <ul class="list-group list-group-flush">
                    <li class="list-group-item"><strong>The Palm Push:</strong> Try to push your finger through your opposite palm.</li>
                    <li class="list-group-item"><strong>The Digital Clock:</strong> Look at a clock, look away, and look back. In dreams, the time usually changes or looks like gibberish.</li>
                    <li class="list-group-item"><strong>The Nose Pinch:</strong> Pinch your nose and try to breathe through it. If you can still breathe, you’re dreaming.</li>
                </ul>
            </div>
