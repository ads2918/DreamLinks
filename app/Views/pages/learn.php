        <h2 class="h3 border-bottom pb-2 mb-4">Advanced Troubleshooting</h2>
        
        <div class="mb-4">
            <h3 class="h5 text-secondary">Why do I wake up as soon as I become lucid?</h3>
            <p>Excitement is the "lucid killer." When you realize you’re dreaming, the rush of adrenaline often wakes you up.</p>
            <div class="alert alert-light border-start border-4 border-primary bg-light">
                <strong>The Fix:</strong> Calm down. Stay still in the dream. <strong>Spin around</strong> or <strong>rub your hands together</strong> in the dream; the sensory input helps "ground" you in the dream world.
            </div>
        </div>

        <div class="row">
            <div class="col-md-6 mb-3">
                <h3 class="h5 text-secondary">Can I get stuck in a lucid dream?</h3>
                <p>No. Your body naturally moves through sleep cycles. You will eventually wake up or slip back into a normal, non-lucid dream.</p>
            </div>
            <div class="col-md-6 mb-3">
                <h3 class="h5 text-secondary">Is sleep paralysis dangerous?</h3>
                <p>It can be scary because you feel heavy and might see "shadows," but it is a natural biological process that keeps you from acting out your dreams. If you encounter it during a WILD attempt, just relax and imagine yourself sliding into a dream scene.</p>
            </div>
